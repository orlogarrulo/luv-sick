const dictionaries = { pt, fr, en };

export type MsgKey = keyof typeof pt;

type I18nValue = {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: MsgKey, vars?: Record<string, string | number>) => string;
};

const I18nContext = createContext<I18nValue | null>(null);

function fill(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? ""));
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("pt");
  useEffect(() => {
    const saved = localStorage.getItem("ct-lang");
    if (saved === "pt" || saved === "fr" || saved === "en") setLangState(saved);
  }, []);
  const value = useMemo<I18nValue>(() => {
    return {
      lang,
      setLang: (next) => {
        setLangState(next);
        localStorage.setItem("ct-lang", next);
      },
      t: (key, vars) => fill(dictionaries[lang][key], vars),
    };
  }, [lang]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("i18n");
  return ctx;
}

export function LangSwitch() {
  const { lang, setLang } = useI18n();
  const options: Lang[] = ["pt", "fr", "en"];
  return (
    <div className="flex rounded-full bg-blue-soft p-1 text-sm font-semibold text-blue">
      {options.map((option) => (
        <button
          key={option}
          type="button"
          onClick={() => setLang(option)}
          className={
            option === lang
              ? "rounded-full bg-blue px-2.5 py-1 text-on-blue"
              : "rounded-full px-2.5 py-1"
          }
          aria-pressed={option === lang}
        >
          {option.toUpperCase()}
        </button>
      ))}
    </div>
  );
}

export function ThemeSwitch() {
  const { t } = useI18n();
  const [night, setNight] = useState(false);
  useEffect(() => {
    const saved = localStorage.getItem("ct-theme");
    const on = saved === "night" || (saved !== "day" && window.matchMedia("(prefers-color-scheme: dark)").matches);
    setNight(on);
    document.documentElement.dataset.theme = on ? "night" : "day";
  }, []);
  return (
    <button
      type="button"
      aria-pressed={night}
      aria-label={night ? t("dayMode") : t("nightMode")}
      title={night ? t("dayMode") : t("nightMode")}
      onClick={() => {
        const next = !night;
        setNight(next);
        document.documentElement.dataset.theme = next ? "night" : "day";
        localStorage.setItem("ct-theme", next ? "night" : "day");
      }}
      className="grid size-11 place-items-center rounded-full text-current"
    >
      {night ? <Sun className="size-5" /> : <Moon className="size-5" />}
    </button>
  );
}
